#!/usr/bin/env python3
"""Validate content/*.json and build src/content.js + dist/artifact.html (single-file preview).

Usage: python3 tools/build.py
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
ORDER = ["capsules_controls", "capsules_engines", "capsules_maneuvers", "capsules_sop", "masterclasses"]

errors = []


def err(where, msg):
    errors.append(f"{where}: {msg}")


def check_qcm(where, qcm, n_expected):
    if len(qcm) != n_expected:
        err(where, f"{len(qcm)} questions (expected {n_expected})")
    for k, q in enumerate(qcm):
        w = f"{where} q{k + 1}"
        if len(q.get("o", [])) != 4:
            err(w, "needs exactly 4 options")
        if not isinstance(q.get("a"), int) or not 0 <= q["a"] < len(q.get("o", [])):
            err(w, "answer index out of range")
        if len(set(q.get("o", []))) != len(q.get("o", [])):
            err(w, "duplicate options")
        for f in ("q", "w"):
            if not q.get(f):
                err(w, f"missing '{f}'")


def load():
    files = sorted(CONTENT.glob("*.json"), key=lambda p: ORDER.index(p.stem) if p.stem in ORDER else 99)
    caps, mcs, ids = [], [], set()
    for f in files:
        for item in json.loads(f.read_text(encoding="utf-8")):
            where = f"{f.name}:{item.get('id')}"
            if item.get("id") in ids:
                err(where, "duplicate id")
            ids.add(item.get("id"))
            if item.get("fleet") not in (None, "both", "NG", "MAX"):
                err(where, "fleet must be both/NG/MAX")
            if item.get("kind") == "masterclass":
                if not item.get("chapters"):
                    err(where, "no chapters")
                check_qcm(where, item.get("qcm", []), 8)
                mcs.append(item)
            else:
                if item.get("cat") not in ("memory", "maneuver", "sop"):
                    err(where, "cat must be memory/maneuver/sop")
                if not item.get("flash", {}).get("title"):
                    err(where, "flash.title missing")
                check_qcm(where, item.get("qcm", []), 5)
                caps.append(item)
    return caps, mcs


def strip(item):
    # sources stay in the repo JSON for review, the app does not need them
    return {k: v for k, v in item.items() if k != "sources"}


def main():
    caps, mcs = load()
    if errors:
        print("Content errors:\n  " + "\n  ".join(errors))
        sys.exit(1)
    data = {"capsules": [strip(c) for c in caps], "masterclasses": [strip(m) for m in mcs]}
    js = "/* Generated by tools/build.py from content/*.json. Do not edit by hand. */\nwindow.NUDGE = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n"
    (ROOT / "src" / "content.js").write_text(js, encoding="utf-8")

    # Single-file preview (published as a claude.ai artifact). The artifact host wraps the page itself.
    css = (ROOT / "src" / "app.css").read_text(encoding="utf-8")
    app = (ROOT / "src" / "app.js").read_text(encoding="utf-8")
    fonts = re.search(r'<link rel="stylesheet" href="(https://fonts[^"]+)">', (ROOT / "index.html").read_text(encoding="utf-8")).group(1)
    page = f"""<title>737 Nudge</title>
<meta name="claude:viewport-fit-sides" content="cover">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="stylesheet" href="{fonts}">
<style>
{css}
</style>
<div class="app" id="app"></div>
<canvas class="burst" id="burst"></canvas>
<script>
{js.replace('</script', '<\\/script')}
</script>
<script>
{app}
</script>
"""
    (ROOT / "dist").mkdir(exist_ok=True)
    (ROOT / "dist" / "artifact.html").write_text(page, encoding="utf-8")
    nq = sum(len(x["qcm"]) for x in caps + mcs)
    print(f"OK: {len(caps)} capsules, {len(mcs)} masterclasses, {nq} questions")


if __name__ == "__main__":
    main()
